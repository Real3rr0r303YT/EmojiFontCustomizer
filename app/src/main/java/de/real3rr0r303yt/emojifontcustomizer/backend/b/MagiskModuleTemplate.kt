package de.real3rr0r303yt.emojifontcustomizer.backend.b

/**
 * Text content of a Magisk / KernelSU / APatch module that replaces the system
 * emoji font. Pure Kotlin so the generated files can be unit-tested.
 */
object MagiskModuleTemplate {

    /** Where AOSP keeps the emoji font; the module mirrors it via systemless overlay. */
    const val EMOJI_PATH = "system/fonts/NotoColorEmoji.ttf"

    /** OEM emoji font names that are replaced too, if the device ships them. */
    val OEM_EMOJI_FILES = listOf(
        "NotoColorEmojiLegacy.ttf",
        "SamsungColorEmoji.ttf",
        "AndroidEmoji-htc.ttf",
        "ColorUniEmoji.ttf",
        "hTC_ColorEmoji.ttf",
        "NotoColorEmojiFlags.ttf",
    )

    private val ID_CHARS = Regex("[^a-z0-9_]")

    fun moduleId(packName: String): String =
        "emojifontcustomizer_" + packName.lowercase().replace(ID_CHARS, "_").trim('_').ifEmpty { "emoji" }

    fun moduleProp(packName: String, appVersion: String): String = buildString {
        appendLine("id=${moduleId(packName)}")
        appendLine("name=Emoji: ${packName.replace('\n', ' ')}")
        appendLine("version=$appVersion")
        appendLine("versionCode=1")
        appendLine("author=Emoji Font Customizer")
        appendLine("description=Replaces the system emoji font. Created with Emoji Font Customizer (GPL-3.0).")
    }

    /** Runs at install time: copy the emoji font over every OEM emoji file that exists. */
    val customizeSh: String = buildString {
        appendLine("#!/system/bin/sh")
        appendLine("# Generated by Emoji Font Customizer")
        appendLine("SRC=\"\$MODPATH/$EMOJI_PATH\"")
        appendLine("for f in ${OEM_EMOJI_FILES.joinToString(" ")}; do")
        appendLine("  if [ -f \"/system/fonts/\$f\" ]; then")
        appendLine("    cp -f \"\$SRC\" \"\$MODPATH/system/fonts/\$f\"")
        appendLine("    ui_print \"- Replacing \$f\"")
        appendLine("  fi")
        appendLine("done")
        appendLine("set_perm_recursive \"\$MODPATH\" 0 0 0755 0644")
    }

    /** Standard Magisk module installer stub. */
    val updateBinary: String = buildString {
        appendLine("#!/sbin/sh")
        appendLine("umask 022")
        appendLine("ui_print() { echo \"\$1\"; }")
        appendLine("OUTFD=\$2")
        appendLine("ZIPFILE=\$3")
        appendLine(". /data/adb/magisk/util_functions.sh")
        appendLine("install_module")
        appendLine("exit 0")
    }

    const val UPDATER_SCRIPT = "#MAGISK\n"
}
