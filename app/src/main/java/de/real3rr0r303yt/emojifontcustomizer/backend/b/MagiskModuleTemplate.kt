package de.real3rr0r303yt.emojifontcustomizer.backend.b

/**
 * Text content of a Magisk / KernelSU / APatch module that replaces the system
 * emoji font. Pure Kotlin so the generated files can be unit-tested.
 */
object MagiskModuleTemplate {

    /** Where AOSP keeps the emoji font; the module mirrors it via systemless overlay. */
    const val EMOJI_PATH = "system/fonts/NotoColorEmoji.ttf"

    /** OEM emoji font names that are replaced too, if the device ships them. */
    val OEM_EMOJI_FILES = listOf(
        "NotoColorEmojiLegacy.ttf",
        "SamsungColorEmoji.ttf",
        "AndroidEmoji-htc.ttf",
        "ColorUniEmoji.ttf",
        "hTC_ColorEmoji.ttf",
        "NotoColorEmojiFlags.ttf",
    )

    private val ID_CHARS = Regex("[^a-z0-9_]")

    fun moduleId(packName: String): String =
        "emojifontcustomizer_" + packName.lowercase().replace(ID_CHARS, "_").trim('_').ifEmpty { "emoji" }

    fun moduleProp(packName: String, appVersion: String): String = buildString {
        appendLine("id=${moduleId(packName)}")
        appendLine("name=Emoji: ${packName.replace('\n', ' ')}")
        appendLine("version=$appVersion")
        appendLine("versionCode=1")
        appendLine("author=Emoji Font Customizer")
        appendLine("description=Replaces the system emoji font. Created with Emoji Font Customizer (GPL-3.0).")
    }

    /**
     * Android 12+ can receive newer emoji fonts through Google Play system updates.
     * They live in /data/fonts and take precedence over /system/fonts, so a module that
     * only replaces /system/fonts appears to do nothing. Removing just the emoji entries
     * makes the system fall back to the (module-provided) /system font.
     */
    private fun StringBuilder.removeUpdatedEmojiFonts() {
        appendLine("for f in \$(find /data/fonts/files -type f -iname '*emoji*' 2>/dev/null); do")
        // Each updated font sits in its own random sub-directory; never delete the root itself.
        appendLine("  d=\"\$(dirname \"\$f\")\"")
        appendLine("  if [ \"\$d\" = /data/fonts/files ]; then rm -f \"\$f\"; else rm -rf \"\$d\"; fi")
        appendLine("done")
    }

    /** Runs at install time: copy the emoji font over every OEM emoji file that exists. */
    val customizeSh: String = buildString {
        appendLine("#!/system/bin/sh")
        appendLine("# Generated by Emoji Font Customizer")
        appendLine("SRC=\"\$MODPATH/$EMOJI_PATH\"")
        appendLine("for f in ${OEM_EMOJI_FILES.joinToString(" ")}; do")
        appendLine("  if [ -f \"/system/fonts/\$f\" ]; then")
        appendLine("    cp -f \"\$SRC\" \"\$MODPATH/system/fonts/\$f\"")
        appendLine("    ui_print \"- Replacing \$f\"")
        appendLine("  fi")
        appendLine("done")
        appendLine("ui_print \"- Removing emoji fonts updated via Google Play (/data/fonts)\"")
        removeUpdatedEmojiFonts()
        appendLine("if [ \"\$KSU\" = \"true\" ] || [ \"\$APATCH\" = \"true\" ]; then")
        appendLine("  ui_print \"! KernelSU/APatch: make sure a mount (overlay) module is installed,\"")
        appendLine("  ui_print \"!   otherwise /system files from modules are not mounted.\"")
        appendLine("fi")
        appendLine("set_perm_recursive \"\$MODPATH\" 0 0 0755 0644")
        appendLine("ui_print \"- Done. Reboot to apply.\"")
    }

    /** Runs early on every boot: updates can re-download the emoji font into /data/fonts. */
    val postFsDataSh: String = buildString {
        appendLine("#!/system/bin/sh")
        appendLine("# Generated by Emoji Font Customizer")
        removeUpdatedEmojiFonts()
    }

    /**
     * Runs after boot: apps using EmojiCompat with downloadable fonts (Gboard, many
     * messengers) read Google Play services' emoji cache instead of the system font.
     * Overwriting the cached files in place keeps their owner, mode and SELinux label.
     */
    val serviceSh: String = buildString {
        appendLine("#!/system/bin/sh")
        appendLine("# Generated by Emoji Font Customizer")
        appendLine("MODDIR=\${0%/*}")
        appendLine("until [ \"\$(getprop sys.boot_completed)\" = \"1\" ]; do sleep 5; done")
        appendLine("SRC=\"\$MODDIR/$EMOJI_PATH\"")
        appendLine("GMS=\"$GMS_FONT_CACHE\"")
        appendLine("[ -d \"\$GMS\" ] || exit 0")
        appendLine("for f in \"\$GMS\"/*[Ee]moji*.ttf; do")
        appendLine("  [ -f \"\$f\" ] && cp -f \"\$SRC\" \"\$f\"")
        appendLine("done")
    }

    /** Google Play services' cache for downloadable fonts (EmojiCompat). */
    const val GMS_FONT_CACHE = "/data/data/com.google.android.gms/files/fonts/opentype"

    /** Standard Magisk module installer stub. */
    val updateBinary: String = buildString {
        appendLine("#!/sbin/sh")
        appendLine("umask 022")
        appendLine("ui_print() { echo \"\$1\"; }")
        appendLine("OUTFD=\$2")
        appendLine("ZIPFILE=\$3")
        appendLine(". /data/adb/magisk/util_functions.sh")
        appendLine("install_module")
        appendLine("exit 0")
    }

    const val UPDATER_SCRIPT = "#MAGISK\n"
}
